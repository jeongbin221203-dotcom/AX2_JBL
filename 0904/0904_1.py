import streamlit as st # 웹 대시보드 화면을 만들기 위한 라이브러리
import pandas as pd # 표 형태의 데이터(DataFrame)를 다루기 위한 라이브러리
import os # 파일 경로 탐색 및 파일 존재 여부 확인용 표준 라이브러리

# ==============================================================================
# [0] 외부 파일 경로 설정
# ==============================================================================
# __file__ : 현재 실행 중인 파이썬 스크립트 파일의 경로
# os.path.dirname(__file__) : 현재 파일이 위치한 폴더 경로 (예: .../0904)
# ".." : 상위 폴더로 이동 (예: .../AX2_JBL)
# "common", "raw_trade_data.csv" : 해당 폴더 내의 파일 지정
# os.path.join을 쓰면 Windows(\)와 Mac/Linux(/)의 경로 구분자를 자동으로 알맞게 연결해 줍니다.

csv_PATH = os.path.join(os.path.dirname(__file__), "..", "common", "raw_trade_data.csv")
#csv_PATH = os.path.join(os.path.dirname(__file__), "raw_trade_data.csv") > 파일이 같은 경로에 있을 경우

# 환율 샘플데이터
# 딕셔너리로 표만들기

# ==============================================================================
# [1] 데이터 준비 (딕셔너리 -> 판다스 DataFrame 변환)
# ==============================================================================
# 주의사항 1: 모든 리스트(열)의 개수(길이)는 반드시 동일해야 함 (안 맞으면 ValueError)
# 주의사항 2: 숫자 데이터는 따옴표 없이 순수 숫자(float/int)로 작성해야 계산/정렬이 가능함
#             (1,390.5처럼 쉼표를 쓰면 2개의 숫자로 분리 인식되므로 주의)

exchange_data = {
    "통화" : ["USD", "EUR", "JPY(100엔)", "CNY"],
    "환율(KRW)" : ["1,390.5", "1,503.2", 930.8, 191.3],
    "전일대비" : [+5.200, -3.100, +1.00, -0.400],
}
# 딕셔너리를 판다스 데이터프레임(2차원 테이블) 구조로 변환
df_exchange = pd.DataFrame(exchange_data) # 파이썬의 DataFrame

# ==============================================================================
# [2] 대시보드 상단 타이틀 및 설명문
# ==============================================================================
st.title("오늘의 환율 대시보드") # 웹페이지 최상단 가장 큰 제목 (HTML의 <h1>)
st.caption("아래 데이터는 실제 환율이 아닌 실습용 샘플데이터") # 작고 연한 보조 설명 글씨

# ==============================================================================
# [3] 환율 표 출력 (st.dataframe vs st.table 차이점)
# ==============================================================================
st.subheader("1) 환율 표 보기") # 중제목 (HTML의 <h3>)
# (1) st.dataframe: 동적 표
# - 사용자가 컬럼명을 클릭해 정렬하거나, 검색/스크롤/다운로드 가능
# - use_container_width=True : 부모 컨테이너(화면) 가로 너비에 맞춰 표를 100% 꽉 채움
st.write("▶ st.dataframe(상호작용 가능한 표)")
st.dataframe(df_exchange, use_container_width=True) # Streamlit의 dataframe / True or False 데이터 길이 조정

# (2) st.table: 정적 표
# - 인터랙션(정렬/스크롤) 없이 화면에 고정된 상태로 깔끔하게 전체를 보여줄 때 사용
# - 주의: st.table에는 use_container_width 파라미터를 사용할 수 없음
st.write("▶ st.table(정적인 표)")
st.table(df_exchange)

exchange_data = {
    "통화" : ["USD", "EUR", "JPY(100엔)", "CNY"],
    "환율(KRW)" : ["1,390.5000", "1,503.2000", 930.8000, 191.3000],
    "전일대비" : [+5.2000, -3.1000, +1.0000, -0.4000],
}
df_exchange = pd.DataFrame(exchange_data)

# 가로 구분선 긋기 (HTML의 <hr>)
st.markdown("---")
# ==============================================================================
# [4] 주요 지표 카드 (st.metric & st.columns 레이아웃)
# ==============================================================================
st.subheader("2) 주요 환율 카드 (st.metric)")

# st.metric(라벨, 현재값, 증감값) 
# st.columns(3): 화면 가로 영역을 3개의 열(Column)로 균등 분할
col1,col2,col3 = st.columns(3)

# with 문을 사용하여 각 열 안에 위젯을 배치
# st.metric(label="항목명", value="현재값", delta="변동폭")
# delta 값이 양수(+)면 초록색 상승 화살표, 음수(-)면 빨간색 하락 화살표가 자동 표시됨
with col1 :
    st.metric(label="USD/KRW", value="1,4500.5", delta="+5.2")
with col2 :
    st.metric(label="USD/KRW", value="1,2500.5", delta="-20.2")
with col3 :
    st.metric(label="USD/KRW", value="987.5", delta="+15.5")



st.markdown("---")
# ==============================================================================
# [5] 외부 CSV 파일 불러오기 및 예외 처리
# ==============================================================================
st.subheader("3) 보너스:무역 원본 데이터 미리보기")
st.write("공용 데이터 파일 raw_trade_data_csv를 읽어온 상위 5행입니다.")

# 1단계: 파일이 실제 해당 경로에 존재하는지 먼저 검사 (FileNotFoundError 방지)
df_trade_raw = pd.read_csv(csv_PATH, encoding="utf-8") #2단계: 기본 UTF-8 인코딩으로 CSV 읽기 시도
# .head(5) : 대용량 데이터 전체가 아닌 맨 위 5개 행만 미리보기로 슬라이싱
st.dataframe(df_trade_raw.head(5), use_container_width=True)
